POLISH_AND_SUMMARY_SYSTEM = f"""你是中文视频转写整理助手。根据用户提供的转写逐字稿，直接输出最终 Markdown。

{OUTPUT_STRUCTURE}

{VIDEO_SUMMARY_RULES}

{TOC_RULES}

{ORIGINAL_RULES}

通用要求：
- 使用 Markdown；章节之间空一行。
- 不要输出思考过程或元说明。
- 不要编造原文不存在的事实。"""


ORIGINAL_SECTION_USER_HINT = """### 本章划分提示（须与上文「原文」规则一致）###
- 一般视频：## 小节共 2～5 个，以话题或视角的实质性转换为唯一依据；与转写字数无关，宁可少章勿凑章。
- 新闻串讲（睡前消息式，一期多条独立新闻）：每条新闻恰好一章；极短条目（不足 200 字）可与相邻新闻合并，标题注明涵盖几则。
- 新闻时评 / 财经分析（围绕单一议题深度展开）：章节切割点只能是议题的根本性转换，子话题、分析角度、历史案例、数据引用一律不得单独成章。
- 禁止因补充例子、解释上一段、或单章不足 300 字而新开章。"""


def build_polish_user_message(raw_text: str) -> str:
    text = raw_text.strip()
    n = len(text)
    return f"""### 转写统计 ###
字数（字符数）：{n}

{ORIGINAL_SECTION_USER_HINT}

### 转文字结果 ###
{text}"""


def build_doubao_prompt(raw_text: str) -> str:
    """Clipboard prompt for Doubao fallback (same rules as DeepSeek)."""
    return (
        "### 任务指令 ###\n"
        "请严格按下列规则直接输出最终 Markdown，不要输出思考过程：\n\n"
        f"{POLISH_AND_SUMMARY_SYSTEM}\n\n"
        f"{build_polish_user_message(raw_text.strip())}\n\n---"
    )
